package packages;
// In this we will learn about packages and Access Modifiers in java.
// Access modifiers are of diff types - public, private, default and protected.
// Public access modifier allows the class, method or variable to be accessed from any other class or package.
// Private access modifier allows the class, method or variable to be accessed only within the same class.
// Default access modifier allows the class, method or variable to be accessed only within the same package.
// Protected access modifier allows the class, method or variable to be accessed within the same package and by subclasses in other packages.
public class E {
    int marks = 50;
}
